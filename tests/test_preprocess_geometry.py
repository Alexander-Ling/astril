"""Geometry regression test for the brain MRI preprocessing pipeline.

A synthetic head phantom is defined in a known reference (co-registration) space. Each "scan" is
generated by sampling the phantom at a known rigid pose on its own grid (oblique / anisotropic /
shared-geometry DWI family), then the full `preprocess_single_brain_mri` pipeline is run with a
provided brainmask.

Covers: the transform chain recorded in each transform record recovers the known pose; every
final `_brain` output matches the phantom resampled directly onto the output grid; all outputs
share one grid; family members reuse the parent transform; and the `native_space` outputs
(single composed transform, header-only placement) land at the known pose.

No patient data is used.
"""
import json
import os
import tempfile
import unittest

import numpy as np

try:
    import SimpleITK as sitk
    from astril.preprocess_single_brain_mri import preprocess_single_brain_mri
except ImportError:  # preprocessing extras not installed
    sitk = None


PATIENT, TIMEPOINT = "SYN", "d0"

# Reference grid (LPS, identity direction), centred on the origin.
REF_SIZE = (128, 128, 112)
REF_SPACING = (1.5, 1.5, 1.5)

# Phantom labels: 0 background, 1 scalp/skull shell, 2 brain, 3 ventricles, 4 lesion,
# 5 small off-centre blob, 6 cerebellum. Brain = labels 2..6.
CONTRAST = {
    "T1c": [0.0, 900.0, 600.0, 100.0, 1000.0, 350.0, 500.0],
    "T2w": [0.0, 400.0, 450.0, 1000.0, 800.0, 150.0, 600.0],
    "DWI-ADC": [0.0, 50.0, 400.0, 1000.0, 600.0, 200.0, 450.0],
    "DWI-TRACE": [0.0, 50.0, 500.0, 100.0, 900.0, 300.0, 600.0],
}

# Scan poses: Euler angles (deg, about x/y/z) and translation (mm), mapping scan-world -> reference.
# Scan grids: size, spacing, and an optional grid tilt about x (deg) to exercise oblique directions.
SCANS = {
    "T1c": dict(rot=(8.0, -4.0, 5.0), trans=(6.0, -9.0, 4.0), size=(128, 140, 120), spacing=(1.5, 1.5, 1.5), tilt=0.0),
    "T2w": dict(rot=(-6.0, 3.0, -7.0), trans=(-5.0, 7.0, -3.0), size=(200, 220, 60), spacing=(1.0, 1.0, 3.0), tilt=5.0),
    "DWI-ADC": dict(rot=(3.0, 6.0, -2.0), trans=(4.0, 3.0, 8.0), size=(100, 110, 80), spacing=(2.0, 2.0, 2.0), tilt=0.0),
    "DWI-TRACE": dict(rot=(3.0, 6.0, -2.0), trans=(4.0, 3.0, 8.0), size=(100, 110, 80), spacing=(2.0, 2.0, 2.0), tilt=0.0),
}
ANCHOR = "T1c"

FINAL_DIMS = (96, 96, 80)
FINAL_VOXELS = (2.0, 2.0, 2.0)

# "accurate" converges to ~0.1 mm on this phantom (the "medium" preset leaves ~1-2 mm of residual
# rotation for cross-contrast pairs), so a 1 mm bound is tight enough to catch composition/inversion
# errors while staying well clear of optimizer noise.
REGISTRATION_STRATEGY = "accurate"
# Default "auto" (GPU when CUDA is available); set ASTRIL_TEST_REGISTRATION_BACKEND=itk or =gpu to pin a backend.
REGISTRATION_BACKEND = os.environ.get("ASTRIL_TEST_REGISTRATION_BACKEND", "auto")
MAX_POSE_ERROR_MM = 1.0
MIN_CONTENT_CORR = 0.97


def _ellipsoid(pts, centre, semi):
    d = (pts - np.asarray(centre)) / np.asarray(semi)
    return (d ** 2).sum(axis=-1) <= 1.0


def _grid_points(img):
    """Physical (LPS) coordinates of every voxel, array shape (z, y, x, 3)."""
    size = img.GetSize()
    idx = np.stack(np.meshgrid(*[np.arange(n) for n in size], indexing="ij"), axis=-1).reshape(-1, 3)
    D = np.asarray(img.GetDirection()).reshape(3, 3)
    pts = np.asarray(img.GetOrigin()) + (idx * np.asarray(img.GetSpacing())) @ D.T
    return pts.reshape(size + (3,)).transpose(2, 1, 0, 3)


def _centred_grid(size, spacing, tilt_deg=0.0):
    img = sitk.Image([int(s) for s in size], sitk.sitkFloat32)
    img.SetSpacing([float(s) for s in spacing])
    t = np.radians(tilt_deg)
    D = np.array([[1, 0, 0], [0, np.cos(t), -np.sin(t)], [0, np.sin(t), np.cos(t)]])
    img.SetDirection(D.ravel().tolist())
    half_extent = (np.asarray(size) - 1) * np.asarray(spacing) / 2.0
    img.SetOrigin((-(D @ half_extent)).tolist())
    return img


def _phantom_labels(ref):
    pts = _grid_points(ref)
    lab = np.zeros(pts.shape[:3], dtype=np.uint8)
    lab[_ellipsoid(pts, (0, 0, 0), (80, 95, 75))] = 1
    lab[_ellipsoid(pts, (0, 0, 0), (68, 83, 62))] = 2
    lab[_ellipsoid(pts, (0, 55, -42), (35, 20, 15))] = 6
    lab[_ellipsoid(pts, (11, 5, 10), (6, 22, 9))] = 3
    lab[_ellipsoid(pts, (-11, 5, 10), (6, 22, 9))] = 3
    lab[_ellipsoid(pts, (30, -35, 20), (12, 12, 12))] = 4
    lab[_ellipsoid(pts, (-35, 30, -18), (8, 8, 8))] = 5
    out = sitk.GetImageFromArray(lab)
    out.CopyInformation(ref)
    return out


def _modality_ref_image(labels, label):
    lut = np.asarray(CONTRAST[label], dtype=np.float32)
    img = sitk.GetImageFromArray(lut[sitk.GetArrayFromImage(labels)])
    img.CopyInformation(labels)
    return sitk.SmoothingRecursiveGaussian(img, 1.0)


def _pose(spec):
    t = sitk.Euler3DTransform()
    t.SetCenter((0.0, 0.0, 0.0))
    t.SetRotation(*[float(np.radians(a)) for a in spec["rot"]])
    t.SetTranslation([float(v) for v in spec["trans"]])
    return t


def _record_chain(output_dir, label):
    """Reference -> native-scan point mapping, built from the saved transform record."""
    with open(os.path.join(output_dir, f"{PATIENT}_{TIMEPOINT}_{label}_transform-record.json")) as f:
        rec = json.load(f)

    def _tfm(rel):
        return sitk.ReadTransform(os.path.normpath(os.path.join(output_dir, rel.lstrip("./"))))

    # Saved transforms map fixed -> moving (Resample convention): coreg ref -> anchor -> scan.
    chain = [_tfm(rec["coregistration"]["transform"])]
    if "initial-registration" in rec:
        chain.append(_tfm(rec["initial-registration"]["transform"]))
    return rec, chain


def _apply_chain(chain, pts):
    out = []
    for p in pts:
        q = tuple(float(v) for v in p)
        for t in chain:
            q = t.TransformPoint(q)
        out.append(q)
    return np.asarray(out)


def _masked_corr(a, b, mask):
    return float(np.corrcoef(a[mask], b[mask])[0, 1])


@unittest.skipIf(sitk is None, "preprocessing extras (SimpleITK) not installed")
class PreprocessGeometryTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory()
        root = cls._tmp.name
        in_dir = os.path.join(root, "in")
        cls.out_dir = os.path.join(root, "out")
        os.makedirs(in_dir)

        ref = _centred_grid(REF_SIZE, REF_SPACING)
        labels = _phantom_labels(ref)
        cls.truth_ref = {lbl: _modality_ref_image(labels, lbl) for lbl in CONTRAST}

        coreg_path = os.path.join(in_dir, "coreg_ref_T1c.nii.gz")
        sitk.WriteImage(cls.truth_ref["T1c"], coreg_path)
        brain = sitk.Cast(sitk.BinaryThreshold(labels, 2, 6, 1, 0), sitk.sitkUInt8)
        mask_path = os.path.join(in_dir, "brainmask_ref.nii.gz")
        sitk.WriteImage(brain, mask_path)

        cls.poses = {}
        cls.grids = {}
        scans = {}
        for lbl, spec in SCANS.items():
            pose = _pose(spec)
            cls.poses[lbl] = pose
            grid = _centred_grid(spec["size"], spec["spacing"], spec["tilt"])
            cls.grids[lbl] = grid
            img = sitk.Resample(cls.truth_ref[lbl], grid, pose, sitk.sitkLinear, 0.0, sitk.sitkFloat32)
            path = os.path.join(in_dir, f"{PATIENT}_{TIMEPOINT}_{lbl}.nii.gz")
            sitk.WriteImage(img, path)
            scans[lbl] = path

        cls.result = preprocess_single_brain_mri(
            output_dir=cls.out_dir,
            scans=scans,
            anchor_label=ANCHOR,
            co_register_path=coreg_path,
            brainmask_path=mask_path,
            anchor_to_coreg_metric="correlation",
            registration_strategy=REGISTRATION_STRATEGY,
            registration_backend=REGISTRATION_BACKEND,
            save_native_space=True,
            final_dims=FINAL_DIMS,
            final_voxels=FINAL_VOXELS,
            patientID=PATIENT,
            timepoint=TIMEPOINT,
            verbose=False,
        )

        # Sample points well inside the brain (reference space) for pose checks.
        rng = np.random.default_rng(0)
        brain_arr = sitk.GetArrayFromImage(sitk.BinaryErode(brain, [5, 5, 5]))
        zyx = np.argwhere(brain_arr > 0)
        zyx = zyx[rng.choice(len(zyx), size=min(400, len(zyx)), replace=False)]
        cls.brain_points = np.asarray([brain.TransformIndexToPhysicalPoint([int(i) for i in p[::-1]]) for p in zyx])

        cls.final_mask = sitk.ReadImage(os.path.join(cls.out_dir, f"{PATIENT}_{TIMEPOINT}_brainmask.nii.gz"))
        cls.final_mask_eroded = sitk.GetArrayFromImage(sitk.BinaryErode(sitk.Cast(cls.final_mask > 0, sitk.sitkUInt8), [2, 2, 2])) > 0

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def _brain_output(self, lbl):
        return sitk.ReadImage(os.path.join(self.out_dir, f"{PATIENT}_{TIMEPOINT}_{lbl}_brain.nii.gz"), sitk.sitkFloat32)

    def test_pipeline_ran(self):
        status, _msg = self.result
        self.assertEqual(status, "RAN")

    def test_recorded_transforms_recover_known_pose(self):
        for lbl in SCANS:
            with self.subTest(label=lbl):
                _rec, chain = _record_chain(self.out_dir, lbl)
                got = _apply_chain(chain, self.brain_points)
                truth_inv = self.poses[lbl].GetInverse()
                want = np.asarray([truth_inv.TransformPoint(tuple(p)) for p in self.brain_points])
                err = np.linalg.norm(got - want, axis=1).max()
                self.assertLess(err, MAX_POSE_ERROR_MM, f"{lbl}: max pose error {err:.2f} mm")

    def test_outputs_share_one_grid(self):
        m = self.final_mask
        self.assertEqual(tuple(m.GetSize()), FINAL_DIMS)
        np.testing.assert_allclose(m.GetSpacing(), FINAL_VOXELS, atol=1e-4)
        for lbl in SCANS:
            for suffix in ("brain", "brain-norm"):
                with self.subTest(label=lbl, suffix=suffix):
                    img = sitk.ReadImage(os.path.join(self.out_dir, f"{PATIENT}_{TIMEPOINT}_{lbl}_{suffix}.nii.gz"))
                    self.assertEqual(img.GetSize(), m.GetSize())
                    np.testing.assert_allclose(img.GetOrigin(), m.GetOrigin(), atol=1e-3)
                    np.testing.assert_allclose(img.GetDirection(), m.GetDirection(), atol=1e-5)
                    np.testing.assert_allclose(img.GetSpacing(), m.GetSpacing(), atol=1e-5)

    def test_brain_outputs_match_phantom(self):
        for lbl in SCANS:
            with self.subTest(label=lbl):
                out = self._brain_output(lbl)
                truth = sitk.Resample(self.truth_ref[lbl], out, sitk.Transform(), sitk.sitkLinear, 0.0, sitk.sitkFloat32)
                r = _masked_corr(sitk.GetArrayFromImage(out), sitk.GetArrayFromImage(truth), self.final_mask_eroded)
                self.assertGreater(r, MIN_CONTENT_CORR, f"{lbl}: r={r:.3f}")

    def test_family_member_reuses_parent_transform(self):
        rec, _ = _record_chain(self.out_dir, "DWI-TRACE")
        self.assertEqual(rec["initial-registration"].get("applied_from_parent"), "DWI-ADC")

    def test_native_space_outputs_placed_at_known_pose(self):
        # native_space outputs keep the scan's voxel grid and only move the header into reference space,
        # so each voxel must land where the known pose sends it (scan world -> reference).
        for lbl in SCANS:
            with self.subTest(label=lbl):
                native = sitk.ReadImage(
                    os.path.join(self.out_dir, "native_space", f"{PATIENT}_{TIMEPOINT}_{lbl}_native_brain.nii.gz")
                )
                grid = self.grids[lbl]
                self.assertEqual(native.GetSize(), grid.GetSize())
                size = np.asarray(grid.GetSize())
                corners = np.array(np.meshgrid(*[[0.25, 0.75]] * 3, indexing="ij")).reshape(3, -1).T
                idxs = [[int(v) for v in np.rint(c * (size - 1))] for c in np.vstack([corners, [0.5, 0.5, 0.5]])]
                got = np.asarray([native.TransformIndexToPhysicalPoint(i) for i in idxs])
                want = np.asarray([self.poses[lbl].TransformPoint(grid.TransformIndexToPhysicalPoint(i)) for i in idxs])
                err = np.linalg.norm(got - want, axis=1).max()
                self.assertLess(err, MAX_POSE_ERROR_MM, f"{lbl}: max native placement error {err:.2f} mm")


if __name__ == "__main__":
    unittest.main()
